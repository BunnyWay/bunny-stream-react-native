import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const packageJson = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const target = new URL('../src/internal/sdkVersion.ts', import.meta.url);
const content = `// Generated by scripts/generate-sdk-version.mjs. Do not edit manually.
export const SDK_VERSION = '${packageJson.version}';
`;
const current = existsSync(target) ? readFileSync(target, 'utf8') : undefined;

if (process.argv.includes('--check')) {
  if (current !== content) {
    console.error('SDK_VERSION is out of date. Run yarn sdk-version:generate.');
    process.exitCode = 1;
  }
} else if (current !== content) {
  writeFileSync(target, content);
}
