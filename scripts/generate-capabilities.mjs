import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { format } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'docs', 'capabilities.json');
const outputPath = path.join(root, 'docs', 'CAPABILITIES.md');
const checkOnly = process.argv.includes('--check');
const allowedStatuses = new Set([
  'supported',
  'partial',
  'unsupported',
  'blocked',
  'platform-only',
]);

const matrix = JSON.parse(await readFile(sourcePath, 'utf8'));

if (matrix.schemaVersion !== 1 || !Array.isArray(matrix.capabilities)) {
  throw new Error('Invalid capability matrix schema');
}

const ids = new Set();
for (const capability of matrix.capabilities) {
  if (!capability.id || ids.has(capability.id)) {
    throw new Error(`Capability IDs must be non-empty and unique: ${capability.id ?? '<empty>'}`);
  }
  ids.add(capability.id);
  for (const platform of ['android', 'ios', 'reactNative']) {
    if (!allowedStatuses.has(capability[platform])) {
      throw new Error(`Invalid ${platform} status for ${capability.id}: ${capability[platform]}`);
    }
  }
}

const escapeCell = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const lines = [
  '<!-- Generated by scripts/generate-capabilities.mjs. Edit docs/capabilities.json instead. -->',
  '',
  '# Capability matrix',
  '',
  'This matrix tracks native SDK support and the public React Native wrapper contract.',
  '',
  '| Area | Android | iOS | React Native | Delivery | Notes |',
  '| --- | --- | --- | --- | --- | --- |',
  ...matrix.capabilities.map(
    (capability) =>
      `| ${escapeCell(capability.area)} | ${capability.android} | ${capability.ios} | ${capability.reactNative} | ${capability.phase} | ${escapeCell(capability.notes)} |`,
  ),
  '',
  '## Status definitions',
  '',
  ...Object.entries(matrix.statuses).map(
    ([status, description]) => `- **${status}** — ${description}`,
  ),
  '',
];
const generated = await format(lines.join('\n'), { parser: 'markdown' });

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    throw new Error('docs/CAPABILITIES.md is stale. Run yarn capabilities:generate.');
  }
} else {
  await writeFile(outputPath, generated);
}
